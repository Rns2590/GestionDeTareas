    // Método para llenar grilla con usuarios
    public void llenarGrilla(JTable tbUsuarios) {
        // Obtener el modelo de la tabla existente (creada desde el diseñador)
        DefaultTableModel modelo = (DefaultTableModel) tbUsuarios.getModel();

        // Limpiar cualquier fila existente en la tabla
        modelo.setRowCount(0);

        // Obtener los datos de los usuarios desde la base de datos
        List<Usuario> listaUsuarios = usuarioDAO.obtenerTodosUsuarios();

        // Recorrer la lista de usuarios y agregar cada uno al modelo
        for (Usuario usuario : listaUsuarios) {
            Object[] fila = {
                usuario.getId(),
                usuario.getNombre(),
                usuario.getApellido(),
                usuario.getUsuario(),
                usuario.getContraseña()
            };
            modelo.addRow(fila);
        }
    }
        
