    private void menuEliminarMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_menuEliminarMouseClicked
        // TODO add your handling code here:
        // Obtener el ID del usuario a eliminar desde el campo de texto
        String idText = txtId.getText();

        if (idText.isEmpty()) {
            // Si el campo de ID está vacío, mostrar un mensaje de error
            JOptionPane.showMessageDialog(this, "Por favor, ingresa un Id válido.", "Error", JOptionPane.ERROR_MESSAGE);
            return; // Salir del método
        }

        int id = Integer.parseInt(idText); // Convertir el Id a entero

        // Mostrar un mensaje de advertencia antes de eliminar
        int respuesta = JOptionPane.showConfirmDialog(this, "¿Estás seguro de que deseas eliminar este usuario?", "Confirmar eliminación", JOptionPane.YES_NO_OPTION);

        if (respuesta == JOptionPane.YES_OPTION) {
            // Si el usuario confirma, proceder a eliminar
            usuarioDAO.eliminarUsuario(id);
            JOptionPane.showMessageDialog(this, "Usuario eliminado exitosamente.", "Éxito", JOptionPane.INFORMATION_MESSAGE);

            // Opcional: Llamar a llenarGrilla para actualizar la tabla después de eliminar
            llenarGrilla(tbUsuarios);
        } else {
            // El usuario canceló la eliminación
            JOptionPane.showMessageDialog(this, "Eliminación cancelada.", "Cancelado", JOptionPane.INFORMATION_MESSAGE);
        }
        
        reiniciarEstadoPantalla();//reiniciar pantalla
    }//GEN-LAST:event_menuEliminarMouseClicked

